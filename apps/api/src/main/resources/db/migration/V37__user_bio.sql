-- **100자다.** 짧으면 한 줄 소개가 되어 모양이 고르고, 스팸이 앉을 자리도 좁다.
-- 길게 열어 두었다가 줄이는 것은 이미 쓴 사람의 글을 자르는 일이라 되돌리기 어렵다.
ALTER TABLE users ADD COLUMN bio VARCHAR(100);
