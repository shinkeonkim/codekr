-- 회원 탈퇴 (#140).
--
-- ## 글과 댓글은 남는다
--
-- **지우면 안 된다.** 대화에서 한쪽 말만 사라지면 남은 말이 뜻을 잃는다 —
-- 답이 달린 질문을 지우면 답을 쓴 사람의 글까지 무의미해진다.
--
-- 그래서 작성자 참조(author_id)는 그대로 두고, **사용자 쪽 상태로 판단해** 화면에
-- "탈퇴한 사용자" 로 그린다. 참조를 끊으면 집계(제출·통계)가 함께 깨지고 되돌릴 수 없다.
--
-- ## 식별 정보는 지운다
--
-- 참조를 남기는 대신 **닉네임과 이메일은 익명 값으로 덮어쓴다.** 개인정보를 남기지 않는
-- 것이 탈퇴의 뜻이다. 여기서 정한 것이 곧 개인정보 처리 방침이 된다.
--
-- 덮어쓰므로 **닉네임은 다시 쓸 수 있게 된다** — 나간 사람이 닉네임을 영구 점유하지 않는다.
ALTER TABLE users ADD COLUMN withdrawn_at TIMESTAMPTZ;

-- 이메일·닉네임 유니크 인덱스가 살아 있는 행에만 걸리도록 되어 있는지 확인이 필요하다.
-- 익명 값으로 덮어쓰므로 충돌하지 않지만, 같은 사람이 두 번 탈퇴할 수는 없다.
CREATE INDEX idx_users_withdrawn ON users (withdrawn_at) WHERE withdrawn_at IS NOT NULL;
