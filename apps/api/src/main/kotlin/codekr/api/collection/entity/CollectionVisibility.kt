package codekr.api.collection.entity

/**
 * 문제집 공개 범위 (#87).
 *
 * **1차에는 공개 목록을 두지 않는다.** 누구나 공개 문제집을 만들 수 있게 하면
 * 스팸·중복·방치가 즉시 생기는데, 지금은 신고도 정리도 할 수 없다. 목록이 곧
 * 쓸 수 없게 되고, 그때는 이미 늦다.
 *
 * 링크 공유만으로도 "커리큘럼을 만들어 나눈다" 는 목적은 이룬다. 공개는 신고와
 * 정렬 기준(인기순 등)이 생긴 뒤에 연다.
 */
enum class CollectionVisibility(val label: String) {
    PRIVATE("나만 보기"),
    UNLISTED("링크가 있는 사람만"),

    /**
     * 목록에 오른다 (#208).
     *
     * **`UNLISTED` 를 남긴다.** 링크 공유는 "아직 다듬는 중" 에 쓰임이 있다 —
     * 공개와 같은 것으로 묶으면 그 단계가 사라진다.
     */
    PUBLIC("누구나 보기"),
}
