package codekr.api.problem.entity

/**
 * 출력 비교 방식 (#279, ADR-0010).
 *
 * **문제 단위다.** 한 문제 안에서 케이스마다 정밀도가 다른 경우는 드물고, 케이스마다
 * 두면 어드민이 채워야 할 칸이 케이스 수만큼 늘어난다.
 */
enum class OutputComparison(val label: String) {
    /** 줄 끝 공백과 끝의 빈 줄만 무시하고 정확히 맞춘다. 지금까지의 동작이다. */
    EXACT("정확 일치"),

    /**
     * 토큰마다 숫자로 읽히면 오차 안에서 비교한다.
     *
     * 실수 답 문제를 내려면 이것이 필요하다 — `3.5` 와 `3.500000` 의 차이는
     * **푸는 사람의 실력이 아니라 언어의 기본 출력 자릿수**에서 온다.
     */
    FLOAT("실수 오차 허용"),

    /**
     * **출제자가 쓴 코드가 판정한다** (#452).
     *
     * 정답이 여럿인 문제 — 조건을 만족하는 아무 배치, 임의 순서, "성질이 맞는가" —
     * 는 기대값과 견줄 수가 없다. 그때는 견주는 대신 물어본다.
     *
     * 기대 출력은 그대로 둔다. 채점 코드가 참고할 수 있고, 없으면 빈 문자열이 간다.
     */
    CHECKER("채점 코드로 판정"),
}
