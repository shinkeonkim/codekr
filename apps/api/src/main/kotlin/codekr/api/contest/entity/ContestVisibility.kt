package codekr.api.contest.entity

/**
 * 대회를 **누가 볼 수 있는가** (#465).
 *
 * **`status` 와 다른 값이다.** `DRAFT` 는 "아직 준비 중" 이고 이것은 "누구에게 보이는가"
 * 다 — 둘을 한 값으로 합치면 "준비 중인 비공개 대회" 와 "열린 비공개 대회" 를 가를 수
 * 없다.
 *
 * 그리고 **참가 승인(#466)과도 직교한다.** 이쪽은 *누가 보는가*, 그쪽은 *누가 내는가* 다 —
 * "비공개 + 자동 승인"(링크만 있으면 참가)과 "공개 + 승인 필요"(누구나 보지만 심사)가
 * 각각 쓸모가 있다.
 *
 * **`PRIVATE` 을 두지 않는다.** 문제집(#87)에는 "나만 보기" 가 뜻이 있지만 **혼자 하는
 * 대회는 없다.**
 */
enum class ContestVisibility(val label: String) {
    /**
     * 링크가 있는 사람만.
     *
     * **비밀이 아니다.** 목록에 없을 뿐이고 slug 를 맞히면 들어온다 — 대회에서 정말
     * 새면 안 되는 것(문제·순위표)은 **시간과 참가 여부가 막는다**(#61·#86), 주소가
     * 막는 것이 아니다.
     */
    UNLISTED("링크가 있는 사람만"),

    /** 누구나. 목록에 뜬다. */
    PUBLIC("누구나 보기"),
}
