package codekr.api.notification.entity

/**
 * 알림 카테고리 (#106).
 *
 * **끄고 켜는 단위가 아니다** (#199). 종류별 수신 거부는 걷어냈다 — 끈 동안의 알림은
 * 아예 만들어지지 않아 되돌릴 수 없었고, 같은 목적의 설정이 두 곳에 살았다.
 *
 * 지금 이 값이 하는 일은 **알림 목록의 탭을 나누는 것**이다 (#135). 화면이 카테고리를
 * 하드코딩하지 않도록 서버가 이 목록과 라벨을 내려준다.
 */
enum class NotificationCategory(val label: String) {
    /** 재채점으로 내 제출 결과가 바뀜 등 (#107). */
    JUDGE("채점"),

    /** 대회 공지, 질의 답변 (#63). */
    CONTEST("대회"),

    /**
     * 내 공개 코드를 누가 읽었는지 (#136).
     *
     * 채점과 따로 둔 이유: 채점 알림은 **내 기록이 바뀐 것**이고 이것은 **남이 내 것을
     * 본 것**이다. 뜻이 다르면 목록에서도 나뉘어야 한다.
     */
    SUBMISSION_VIEW("코드 열람"),

    /**
     * 내 글·내 댓글에 답이 달림 (#212).
     *
     * **하나로 둔다.** 끄는 기능이 없으므로(#199) 카테고리를 나누는 이유는 "끄기 단위"
     * 가 아니라 **"목록 탭에서 찾는 단위"** 뿐이다. 멘션(#214)이 오면 그때 나눌지 다시
     * 본다 — 탭이 늘수록 각 탭이 비어 보인다.
     */
    COMMENT("댓글"),

    /** 점검·정책 변경. */
    /**
     * 뱃지를 받거나 잃음 (#558).
     *
     * 채점과 따로 둔 이유: 채점 알림은 **내가 낸 것의 결과**이고 이것은 **규칙이 바뀌어
     * 내 기록이 바뀐 것**이다. 특히 회수는 사용자가 아무것도 안 했는데 사라지는 것이라,
     * 채점 알림 사이에 묻히면 안 된다.
     */
    BADGE("뱃지"),

    SYSTEM("시스템"),
}
