/**
 * 페이지 가로 폭 (#599).
 *
 * **폭을 정하는 규칙이 없어서 페이지마다 손으로 골랐다.** `AppShell` 이 이미
 * `max-w-6xl` 을 주는데 설정은 `max-w-2xl`, 질문 작성은 `max-w-3xl` 로 다시 좁혔다.
 * 그래서 문제 목록에서 설정으로 넘어가면 **내용이 갑자기 안으로 빨려 들어간다.**
 *
 * 좁은 것 자체가 틀린 것은 아니다 — 로그인 폼이 1152px 로 벌어지면 그것대로 이상하다.
 * 틀린 것은 **같은 뜻의 페이지가 서로 다른 폭을 쓰는 것**이다. 그래서 폭을 세 단으로
 * 두고 이름을 붙였다.
 *
 * | 단 | 폭 | 어떤 페이지가 |
 * |---|---|---|
 * | `wide` | 셸 기본 (`max-w-6xl`) | 목록·표·대시보드처럼 **가로를 쓰는** 것 |
 * | `reading` | `max-w-4xl` | 긴 글을 **읽는** 것 — 줄이 길면 눈이 되돌아오지 못한다 |
 * | `form` | `max-w-md` | 칸 몇 개로 끝나는 것 — 넓히면 이름표와 칸이 멀어진다 |
 *
 * `wide` 가 빈 문자열인 것은 **셸이 이미 그 폭을 주기 때문**이다. 여기서 다시 적으면
 * 셸의 값을 바꿀 때 두 곳을 고쳐야 한다.
 *
 * `pageWidth.test.ts` 가 **이 파일 밖에서 `mx-auto` 와 `max-w-*xl` 을 같이 쓰는 것**을
 * 막는다. 색 토큰(#286)·층 토큰(#578)이 같은 방식으로 갈라졌고 같은 방식으로 막았다.
 */

/**
 * 껍데기의 폭. 본문·머리말·꼬리말이 **같은 줄에 서야** 하므로 셋이 이 값을 함께 쓴다.
 *
 * 전에는 세 곳에 `max-w-6xl` 이 따로 적혀 있었다 — 하나만 바꾸면 머리말과 본문의
 * 왼쪽 끝이 어긋나는데, 그렇게 되기 전까지는 아무 일도 일어나지 않는다.
 */
export const SHELL_WIDTH = "mx-auto w-full max-w-6xl px-4";

export const PAGE_WIDTH = {
  wide: "",
  reading: "mx-auto w-full max-w-4xl",
  form: "mx-auto w-full max-w-md",
} as const;

export type PageWidth = keyof typeof PAGE_WIDTH;
