import "server-only";

/**
 * 서버가 API 를 부를 주소 (#271).
 *
 * **`NEXT_PUBLIC_` 이 아니다.** 브라우저는 이 값을 알 필요가 없고, 번들에 들어가면
 * 클러스터 내부 주소가 밖으로 새어 나간다. `server-only` 를 import 해서 클라이언트
 * 컴포넌트가 실수로 가져다 쓰면 **빌드가 깨지게** 해 둔다.
 *
 * ## 왜 브라우저 주소를 못 쓰는가
 *
 * 이 웹은 모든 API 호출이 브라우저에서 일어난다는 전제 위에 서 있다 (`shared/config`).
 * 브라우저는 자기가 열린 주소로 상대 경로를 보내면 되지만, **서버는 자기가 어느
 * 주소로 노출되는지 모른다.** 요청의 Host 를 쓸 수도 있으나 그것은 밖에서 온 값이라
 * 서버끼리 부르는 주소로 삼을 수 없다.
 *
 * ## 없으면 없는 대로 돈다
 *
 * 로컬 개발과 미리보기에는 이 값이 없다. 그때 sitemap 이 깨지면 안 되므로,
 * 부르는 쪽이 **비었으면 건너뛴다** (`sitemap.ts`).
 */
export const API_INTERNAL_BASE_URL = process.env.API_INTERNAL_BASE_URL ?? "";
